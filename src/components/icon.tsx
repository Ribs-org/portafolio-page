const ALIASES: Record<string, string> = {
  twitter: 'x',
  ig: 'instagram',
  tt: 'tiktok',
  yt: 'youtube',
}

export const ICON_NAMES = [...Object.keys(BRANDS), ...Object.keys(LUCIDE)].sort()

export function Icon({ name, className }: { name?: string | null; className?: string }) {
  const raw = (name ?? '').toLowerCase().trim()
  const key = ALIASES[raw] ?? raw

  const path = BRANDS[key]
  if (path) {
    return (
      <svg viewBox="0 0 24 24" fill="currentColor" className={className} aria-hidden>
        <path d={path} />
      </svg>
    )
  }

  const Lucide = LUCIDE[key]
  if (Lucide) return <Lucide className={className} aria-hidden />

  // Unknown names are treated as a literal emoji, so any glyph works as an icon.
  if (raw) {
    return (
      <span className={className} style={{ display: 'grid', placeItems: 'center' }} aria-hidden>
        {name}
      </span>
    )
  }

  return <Globe className={className} aria-hidden />
}
